SET lc_time_names = 'pt_BR';

DROP DATABASE IF EXISTS ACADEMIA;

CREATE DATABASE ACADEMIA;

USE ACADEMIA;

CREATE TABLE ALUNO (
    ID_ALUNO INT PRIMARY KEY AUTO_INCREMENT,
    NOME_ALUNO VARCHAR(100) NOT NULL,
    CPF_ALUNO VARCHAR(14) NOT NULL UNIQUE,
    DATA_NASCIMENTO_ALUNO DATE NOT NULL,
    TELEFONE_ALUNO VARCHAR(20),
    EMAIL_ALUNO VARCHAR(100),
    DATA_CADASTRO_ALUNO DATE NOT NULL DEFAULT (CURRENT_DATE),
    STATUS_ALUNO VARCHAR(20) NOT NULL DEFAULT 'Ativo'
);

CREATE TABLE PROFESSOR (
    ID_PROFESSOR INT PRIMARY KEY AUTO_INCREMENT,
    NOME_PROFESSOR VARCHAR(100) NOT NULL,
    CPF_PROFESSOR VARCHAR(14) NOT NULL UNIQUE,
    CREF VARCHAR(20) NOT NULL UNIQUE,
    TELEFONE_PROFESSOR VARCHAR(20),
    EMAIL_PROFESSOR VARCHAR(100)
);

CREATE TABLE PLANO (
    ID_PLANO INT PRIMARY KEY AUTO_INCREMENT,
    NOME_PLANO VARCHAR(100) NOT NULL,
    DURACAO_PLANO INT NOT NULL,
    VALOR_PLANO DECIMAL(10,2) NOT NULL,
    DESCRICAO_PLANO VARCHAR(255),
    STATUS_PLANO VARCHAR(20) NOT NULL DEFAULT 'Ativo'
);

CREATE TABLE MATRICULA (
    ID_MATRICULA INT PRIMARY KEY AUTO_INCREMENT,
    ID_ALUNO_FK INT NOT NULL,
    ID_PLANO_FK INT NOT NULL,
    DATA_INICIO DATE NOT NULL,
    DATA_FIM DATE NOT NULL,
    STATUS_MATRICULA VARCHAR(20) NOT NULL DEFAULT 'Ativa',

    FOREIGN KEY (ID_ALUNO_FK) REFERENCES ALUNO (ID_ALUNO),

    FOREIGN KEY (ID_PLANO_FK) REFERENCES PLANO (ID_PLANO)
);

/*
A gente utiliza as chaves estrangeiras porque elas permitem relacionar as tabelas através dos IDs. 
Assim, em vez de repetir o nome do aluno e do plano em cada matrícula, armazenamos seus identificadores. 
Isso evita duplicação de informações e facilita a manutenção dos dados.
*/

CREATE TABLE PAGAMENTO (
    ID_PAGAMENTO INT PRIMARY KEY AUTO_INCREMENT,
    ID_MATRICULA_FK INT NOT NULL,
    VALOR_PAGAMENTO DECIMAL(10,2) NOT NULL,
    DATA_VENCIMENTO DATE NOT NULL,
    DATA_PAGAMENTO DATE,
    FORMA_PAGAMENTO VARCHAR(30),
    STATUS_PAGAMENTO VARCHAR(20) NOT NULL DEFAULT 'Pendente',

    FOREIGN KEY (ID_MATRICULA_FK) REFERENCES MATRICULA (ID_MATRICULA)
);

CREATE TABLE EXERCICIOS (
    ID_EXERCICIOS INT PRIMARY KEY AUTO_INCREMENT,
    NOME_EXERCICIO VARCHAR(100) NOT NULL,
    GRUPO_MUSCULAR VARCHAR(50) NOT NULL,
    DESCRICAO_EXERCICIO VARCHAR(255),
    EQUIPAMENTOS VARCHAR(255)
);

CREATE TABLE TREINO (
    ID_TREINO INT PRIMARY KEY AUTO_INCREMENT,
    ID_ALUNO_FK INT NOT NULL,
    ID_PROFESSOR_FK INT NOT NULL,
    NOME_TREINO VARCHAR(50) NOT NULL,
    DATA_CRIACAO DATE NOT NULL DEFAULT (CURRENT_DATE),
    OBSERVACOES VARCHAR(255),

    FOREIGN KEY (ID_ALUNO_FK) REFERENCES ALUNO (ID_ALUNO),

    FOREIGN KEY (ID_PROFESSOR_FK) REFERENCES PROFESSOR (ID_PROFESSOR)
);

CREATE TABLE TREINO_EXERCICIO (
    ID_TREINO_EXERCICIO INT PRIMARY KEY AUTO_INCREMENT,
    ID_TREINO_FK INT NOT NULL,
    ID_EXERCICIOS_FK INT NOT NULL,
    ORDEM_EXERCICIO INT NOT NULL DEFAULT 1,
    SERIES INT,
    REPETICOES VARCHAR(30),
    CARGA DECIMAL(6,2),
    OBSERVACOES VARCHAR(255),

    FOREIGN KEY (ID_TREINO_FK) REFERENCES TREINO (ID_TREINO) ON DELETE CASCADE,

    FOREIGN KEY (ID_EXERCICIOS_FK) REFERENCES EXERCICIOS (ID_EXERCICIOS)
);

/*
um treino ele pode ter vários exercícios e um exercício ele pode aparecer em vários treinos. 
Então a gente criou o treino_exercício pra ser como um intermediário pq cada um dos exercícios 
pode ter diferentes séries, repetições, cargas e observações e ordens para um aluno específico
*/

CREATE TABLE AVALIACAO_FISICA (
    ID_AVALIACAO INT PRIMARY KEY AUTO_INCREMENT,
    ID_ALUNO_FK INT NOT NULL,
    PESO DECIMAL(5,2) NOT NULL,
    ALTURA DECIMAL(4,2) NOT NULL,
    PERCENTUAL_GORDURA DECIMAL(5,2),
    MASSA_MAGRA DECIMAL(5,2),
    BRACO DECIMAL(5,2),
    CINTURA DECIMAL(5,2),
    QUADRIL DECIMAL(5,2),
    DATA_AVALIACAO DATE NOT NULL DEFAULT (CURRENT_DATE),

    FOREIGN KEY (ID_ALUNO_FK) REFERENCES ALUNO (ID_ALUNO)
);

/*
cada avaliação física é armazenada como um novo registro na tabela AVALIACAO_FISICA, 
com um ID próprio e uma chave estrangeira que identifica o aluno. 
Então, quando o aluno faz uma nova avaliação, ela é cadastrada separadamente, mantendo o histórico das avaliações anteriores.
*/

